import type { ScenePack, TechnicalSpec } from "@/types/content";

const GB = 1024 ** 3;
const MB = 1024 ** 2;

function tech(partial: Partial<TechnicalSpec> & Pick<TechnicalSpec, "resolution" | "fps" | "clipCount" | "fileSizeBytes">): TechnicalSpec {
  return { format: "MP4 (H.264)", aspectRatio: "16:9", ...partial };
}

type Seed = Omit<ScenePack, "previews" | "editing" | "version" | "status" | "featured" | "createdAt" | "updatedAt" | "publishedAt"> &
  Partial<Pick<ScenePack, "previews" | "editing" | "version" | "status" | "featured" | "updatedAt">> & {
    publishedAt: string | null;
  };

function pack(seed: Seed): ScenePack {
  const published = seed.publishedAt ?? "2026-09-01T12:00:00.000Z";
  return {
    previews: [],
    editing: {},
    version: "1.0",
    status: "published",
    featured: false,
    createdAt: published,
    updatedAt: published,
    ...seed,
  };
}

